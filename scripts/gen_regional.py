#!/usr/bin/env python3
# Generates build_regional.sql from scripts/_regional/{entities,relationships}.json — deepening the
# European regional polytheisms (v1.77.0): Slavic (West-Slavic temple gods + folk spirits), Finnish
# (Kalevala), Baltic, and the newly-added Basque, Sámi, and Hungarian/Magyar pantheons.
# Prefix-driven tradition/period; per-entity source; 5 new sources, 3 new periods. Idempotent + self-validating.
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); F = os.path.join(HERE, "_regional")

NEW_PERIODS = [
 ("PER_BASQUE_PAGAN","Basque Pre-Christian Period",-500,1000),
 ("PER_SAMI_TRADITIONAL","Sámi Traditional / Pre-Christian",-500,1700),
 ("PER_HUNGARIAN_PAGAN","Pre-Christian Magyar Period",-500,1000),
]
NEW_SOURCES = [
 ("SRC_SAXO_GESTA","primary text","Saxo Grammaticus, Gesta Danorum (c. 1200) — the West-Slavic temple cults of Rügen","Slavic"),
 ("SRC_HELMOLD_CHRONICA","primary text","Helmold of Bosau, Chronica Slavorum (c. 1170) — the Polabian and Pomeranian Slavic gods","Slavic"),
 ("SRC_BARANDIARAN","secondary scholarship","José Miguel de Barandiarán, Mitología Vasca","Basque"),
 ("SRC_SAMI_RELIGION","secondary scholarship","Scholarship on the pre-Christian Sámi noaidi religion (e.g. Bäckman & Hultkrantz)","Sámi"),
 ("SRC_HUNGARIAN_MYTH","secondary scholarship","Scholarly reconstruction of pre-Christian Magyar religion (e.g. Róheim; Diószegi)","Hungarian"),
]
TRAD = {"SLAV":"Slavic","FINN":"Finnish","BALT":"Baltic","BSQ":"Basque","SAMI":"Sámi","HUN":"Hungarian"}
PERIOD = {"SLAV":"PER_SLAV_PAGAN","FINN":"PER_FINN_TRADITIONAL","BALT":"PER_BALT_PAGAN",
          "BSQ":"PER_BASQUE_PAGAN","SAMI":"PER_SAMI_TRADITIONAL","HUN":"PER_HUNGARIAN_PAGAN"}
PRIMARY_SRCS = {"SRC_PRIMARY_CHRONICLE_PVL","SRC_SAXO_GESTA","SRC_HELMOLD_CHRONICA","SRC_KALEVALA","SRC_AGRICOLA_PRIMER"}
def pfx(eid): return eid.split("_")[1]
def conf_norm(c):
    c=(c or "").lower()
    return c if c in ("high","medium","low") else {"a":"high","b":"medium","c":"low","d":"low"}.get(c,"medium")
def q(x): return "'" + str(x).replace("'","''") + "'"

ents = json.load(open(os.path.join(F,"entities.json")))
rels = json.load(open(os.path.join(F,"relationships.json")))

out=["-- build_regional.sql  (GENERATED by gen_regional.py) — v1.77.0",
     "-- European regional polytheisms: Slavic (temple gods + folk spirits), Finnish, Baltic,",
     "-- and the new Basque, Sámi, and Hungarian/Magyar pantheons.",
     "-- %d new entities, %d edges. Idempotent + self-validating." % (len(ents), len(rels)),
     "BEGIN;",""]
out.append("INSERT INTO periods (period_id, period_name, start_year, end_year) VALUES")
out.append(",\n".join(" (%s,%s,%d,%d)"%(q(a),q(b),c,d) for (a,b,c,d) in NEW_PERIODS)+"\nON CONFLICT (period_id) DO NOTHING;")
out.append("")
out.append("INSERT INTO sources (source_id, source_type, title, scope) VALUES")
out.append(",\n".join(" (%s,%s,%s,%s)"%(q(a),q(b),q(c),q(dd)) for (a,b,c,dd) in NEW_SOURCES)+"\nON CONFLICT (source_id) DO NOTHING;")
out.append("")
out.append("CREATE TEMP TABLE _e(id text,name text,trad text,etype text,cat text,dom text,conf text,note text) ON COMMIT DROP;")
out.append("INSERT INTO _e VALUES")
out.append(",\n".join(" (%s,%s,%s,%s,%s,%s,%s,%s)"%(q(e["id"]),q(e["name"]),q(TRAD[pfx(e["id"])]),q(e["type"]),q(e["cat"]),q(e["dom"]),q(e["conf"]),q(e["note"])) for e in ents)+";")
out.append("""
INSERT INTO entities (entity_id,canonical_name,tradition,entity_type,category,primary_domains,cult_scope,evidence_confidence,review_status,inclusion_basis,earth_association_score,chthonic_flag,serpent_flag,short_note)
SELECT id,name,trad,etype,cat,dom,'regional',conf,'candidate_verified_name','European regional polytheism deepening (v1.77.0)',0,false,false,note FROM _e
ON CONFLICT (entity_id) DO NOTHING;
""")
out.append("CREATE TEMP TABLE _s(id text,src text,note text,etype text) ON COMMIT DROP;")
out.append("INSERT INTO _s VALUES")
out.append(",\n".join(" (%s,%s,%s,%s)"%(q(e["id"]),q(e["src"]),q(e["note"]),q("primary text attestation" if e["src"] in PRIMARY_SRCS else "scholarly attestation")) for e in ents)+";")
out.append("""
INSERT INTO entity_sources (entity_id,source_id,evidence_type,source_note)
SELECT s.id,s.src,s.etype,s.note FROM _s s
WHERE EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=s.id) AND EXISTS(SELECT 1 FROM sources x WHERE x.source_id=s.src)
ON CONFLICT DO NOTHING;
""")
out.append("CREATE TEMP TABLE _p(id text,per text,note text) ON COMMIT DROP;")
out.append("INSERT INTO _p VALUES")
out.append(",\n".join(" (%s,%s,%s)"%(q(e["id"]),q(PERIOD[pfx(e["id"])]),q(e["note"])) for e in ents)+";")
out.append("""
INSERT INTO entity_periods (entity_id,period_id,confidence,rationale,source_id,review_status)
SELECT p.id,p.per,'high',p.note,(SELECT es.source_id FROM entity_sources es WHERE es.entity_id=p.id ORDER BY es.source_id LIMIT 1),'reviewed'
FROM _p p
WHERE EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=p.id) AND EXISTS(SELECT 1 FROM periods x WHERE x.period_id=p.per)
ON CONFLICT DO NOTHING;
""")
out.append("CREATE TEMP TABLE _r(s text,t text,o text,c text,ra text) ON COMMIT DROP;")
out.append("INSERT INTO _r VALUES")
out.append(",\n".join(" (%s,%s,%s,%s,%s)"%(q(r["s"]),q(r["t"]),q(r["o"]),q(conf_norm(r.get("c"))),q(r["ra"])) for r in rels)+";")
out.append("""
\\echo '--- REJECTED edges (bad id/type/source) — review these ---'
SELECT r.s,r.t,r.o FROM _r r
WHERE NOT (EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=r.s)
  AND EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=r.o)
  AND EXISTS(SELECT 1 FROM relationship_types y WHERE y.relationship_type=r.t)
  AND EXISTS(SELECT 1 FROM entity_sources es WHERE es.entity_id=r.s));

INSERT INTO entity_relationships(subject_entity_id,relationship_type,object_entity_id,confidence,rationale,source_id,review_status)
SELECT r.s,r.t,r.o,r.c,r.ra,
  (SELECT es.source_id FROM entity_sources es WHERE es.entity_id=r.s ORDER BY es.source_id LIMIT 1),'reviewed'
FROM _r r
WHERE EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=r.s)
  AND EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=r.o)
  AND EXISTS(SELECT 1 FROM relationship_types y WHERE y.relationship_type=r.t)
  AND EXISTS(SELECT 1 FROM entity_sources es WHERE es.entity_id=r.s)
ON CONFLICT (subject_entity_id,relationship_type,object_entity_id) DO NOTHING;

COMMIT;
""")
open(os.path.join(HERE,"build_regional.sql"),"w").write("\n".join(out))
print("wrote build_regional.sql: %d entities, %d edges, %d periods, %d sources" % (len(ents),len(rels),len(NEW_PERIODS),len(NEW_SOURCES)))
