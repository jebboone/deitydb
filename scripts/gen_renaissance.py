#!/usr/bin/env python3
# Generates build_renaissance.sql from scripts/_renaissance/{entities,relationships}.json — the
# Renaissance angelic & planetary magic cluster: the Shem ha-Mephorash 72 angels (Kircher),
# Agrippa's planetary Intelligences & Spirits (De occulta phil. II.22), and the Olympic Spirits
# (Arbatel). v1.69.0. Tradition 'Renaissance Esoteric', reuses period PER_EARLY_MODERN_OCCULT.
# Idempotent + self-validating. Confidence derived by relationship type (member_of=high, else medium).
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); F = os.path.join(HERE, "_renaissance")
TRAD = "Renaissance Esoteric"
PERIOD_ID = "PER_EARLY_MODERN_OCCULT"   # created in v1.68.0

NEW_PERIODS = []  # PER_EARLY_MODERN_OCCULT already exists
NEW_SOURCES = [
 ("SRC_KIRCHER_OEDIPUS","primary text","Athanasius Kircher, Oedipus Aegyptiacus (1652-54) — the canonical 72-name roster of the Shem ha-Mephorash","Renaissance Esoteric"),
 ("SRC_ARBATEL","primary text","Arbatel de magia veterum (Basel, 1575) — the seven Olympic Spirits","Renaissance Esoteric"),
 ("SRC_RUDD_GOETIA","primary text","Thomas Rudd, Treatise on Angel Magic / 'The Goetia of Dr Rudd' (17th c.; ed. Skinner & Rankine) — the Shem-angel vs Goetia-demon pairing","Renaissance Esoteric"),
]
# SRC_AGRIPPA_OCCULTA already exists (added v1.67.2).
PRIMARY_SRCS = {"SRC_KIRCHER_OEDIPUS","SRC_ARBATEL","SRC_RUDD_GOETIA","SRC_AGRIPPA_OCCULTA"}
def q(x): return "'" + str(x).replace("'","''") + "'"
def conf_for(t): return "high" if t == "member_of" else "medium"

ents = json.load(open(os.path.join(F,"entities.json")))
rels = json.load(open(os.path.join(F,"relationships.json")))

out=["-- build_renaissance.sql  (GENERATED by gen_renaissance.py) — v1.69.0",
     "-- Renaissance angelic & planetary magic: the Shem ha-Mephorash 72 angels (Kircher),",
     "-- Agrippa's planetary Intelligences & Spirits, and the Olympic Spirits (Arbatel).",
     "-- %d new entities, %d edges. Idempotent + self-validating." % (len(ents), len(rels)),
     "BEGIN;",""]
if NEW_PERIODS:
    out.append("INSERT INTO periods (period_id, period_name, start_year, end_year) VALUES")
    out.append(",\n".join(" (%s,%s,%d,%d)"%(q(a),q(b),c,d) for (a,b,c,d) in NEW_PERIODS)+"\nON CONFLICT (period_id) DO NOTHING;")
    out.append("")
out.append("INSERT INTO sources (source_id, source_type, title, scope) VALUES")
out.append(",\n".join(" (%s,%s,%s,%s)"%(q(a),q(b),q(c),q(dd)) for (a,b,c,dd) in NEW_SOURCES)+"\nON CONFLICT (source_id) DO NOTHING;")
out.append("")
# entities
out.append("CREATE TEMP TABLE _e(id text,name text,etype text,cat text,dom text,conf text,note text) ON COMMIT DROP;")
out.append("INSERT INTO _e VALUES")
out.append(",\n".join(" (%s,%s,%s,%s,%s,%s,%s)"%(q(e["id"]),q(e["name"]),q(e["type"]),q(e["cat"]),q(e["dom"]),q(e["conf"]),q(e["note"])) for e in ents)+";")
out.append("""
INSERT INTO entities (entity_id,canonical_name,tradition,entity_type,category,primary_domains,cult_scope,evidence_confidence,review_status,inclusion_basis,earth_association_score,chthonic_flag,serpent_flag,short_note)
SELECT id,name,%s,etype,cat,dom,'literary',conf,'candidate_verified_name','Renaissance angelic/planetary magic (v1.69.0)',0,false,false,note FROM _e
ON CONFLICT (entity_id) DO NOTHING;
""" % q(TRAD))
# sources per entity
out.append("CREATE TEMP TABLE _s(id text,src text,note text,etype text) ON COMMIT DROP;")
out.append("INSERT INTO _s VALUES")
srows=[]
for e in ents:
    s=e["src"]; et = "primary text attestation" if s in PRIMARY_SRCS else "scholarly attestation"
    srows.append(" (%s,%s,%s,%s)"%(q(e["id"]),q(s),q(e["note"]),q(et)))
out.append(",\n".join(srows)+";")
out.append("""
INSERT INTO entity_sources (entity_id,source_id,evidence_type,source_note)
SELECT s.id,s.src,s.etype,s.note FROM _s s
WHERE EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=s.id) AND EXISTS(SELECT 1 FROM sources x WHERE x.source_id=s.src)
ON CONFLICT DO NOTHING;
""")
# periods per entity
out.append("CREATE TEMP TABLE _p(id text,per text,note text) ON COMMIT DROP;")
out.append("INSERT INTO _p VALUES")
out.append(",\n".join(" (%s,%s,%s)"%(q(e["id"]),q(PERIOD_ID),q(e["note"])) for e in ents)+";")
out.append("""
INSERT INTO entity_periods (entity_id,period_id,confidence,rationale,source_id,review_status)
SELECT p.id,p.per,'high',p.note,(SELECT es.source_id FROM entity_sources es WHERE es.entity_id=p.id ORDER BY es.source_id LIMIT 1),'reviewed'
FROM _p p
WHERE EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=p.id) AND EXISTS(SELECT 1 FROM periods x WHERE x.period_id=p.per)
ON CONFLICT DO NOTHING;
""")
# relationships (confidence derived by type; per-edge src override else subject's own source)
out.append("CREATE TEMP TABLE _r(s text,t text,o text,c text,ra text,src text) ON COMMIT DROP;")
out.append("INSERT INTO _r VALUES")
rrows=[]
for r in rels:
    src = r.get("src","")
    rrows.append(" (%s,%s,%s,%s,%s,%s)"%(q(r["s"]),q(r["t"]),q(r["o"]),q(conf_for(r["t"])),q(r["ra"]),q(src)))
out.append(",\n".join(rrows)+";")
out.append("""
\\echo '--- REJECTED edges (bad id/type/source) — review these ---'
SELECT r.s,r.t,r.o FROM _r r
WHERE NOT (EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=r.s)
  AND EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=r.o)
  AND EXISTS(SELECT 1 FROM relationship_types y WHERE y.relationship_type=r.t)
  AND EXISTS(SELECT 1 FROM entity_sources es WHERE es.entity_id=r.s));

INSERT INTO entity_relationships(subject_entity_id,relationship_type,object_entity_id,confidence,rationale,source_id,review_status)
SELECT r.s,r.t,r.o,r.c,r.ra,
  COALESCE(NULLIF(r.src,''),(SELECT es.source_id FROM entity_sources es WHERE es.entity_id=r.s ORDER BY es.source_id LIMIT 1)),'reviewed'
FROM _r r
WHERE EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=r.s)
  AND EXISTS(SELECT 1 FROM entities e WHERE e.entity_id=r.o)
  AND EXISTS(SELECT 1 FROM relationship_types y WHERE y.relationship_type=r.t)
  AND EXISTS(SELECT 1 FROM entity_sources es WHERE es.entity_id=r.s)
ON CONFLICT (subject_entity_id,relationship_type,object_entity_id) DO NOTHING;

COMMIT;
""")
open(os.path.join(HERE,"build_renaissance.sql"),"w").write("\n".join(out))
print("wrote build_renaissance.sql: %d entities, %d edges, %d new periods, %d new sources" % (len(ents),len(rels),len(NEW_PERIODS),len(NEW_SOURCES)))
